import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Marked, Renderer } from 'marked';
import { format, resolveConfig } from 'prettier';

const workspaceRoot = new URL('../', import.meta.url);
const docsInputDirectory = new URL('apps/showcase/public/docs/', workspaceRoot);
const docsOutputFile = new URL('apps/showcase/src/app/docs/docs-html-registry.ts', workspaceRoot);
const searchIndexOutputFile = new URL('apps/showcase/src/app/docs/docs-search-index.ts', workspaceRoot);

/** Plain-text budget per search section so the emitted index stays lean. */
const SEARCH_SECTION_TEXT_LIMIT = 1500;

const slugifyMarkdownHeading = (value) =>
  value
    .toLowerCase()
    .trim()
    .replace(/[`'"]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const getUniqueMarkdownHeadingId = (baseId, usedIds) => {
  let id = baseId;
  let index = 2;

  while (usedIds.has(id)) {
    id = `${baseId}-${index}`;
    index += 1;
  }

  return id;
};

const createRenderer = () => {
  const renderer = new Renderer();
  const headings = [];
  const usedHeadingIds = new Set();

  renderer.heading = function heading({ tokens, depth, text }) {
    const headingHtml = this.parser.parseInline(tokens);
    const baseId = slugifyMarkdownHeading(text);

    if (!baseId) {
      return `<h${depth}>${headingHtml}</h${depth}>\n`;
    }

    const id = getUniqueMarkdownHeadingId(baseId, usedHeadingIds);

    usedHeadingIds.add(id);
    headings.push({ depth, id });

    return `<h${depth}>${headingHtml}</h${depth}>\n`;
  };

  return { renderer, headings };
};

const renderMarkdown = (markdown) => {
  const { renderer, headings } = createRenderer();
  const html = new Marked({
    async: false,
    breaks: false,
    gfm: true,
    pedantic: false,
    renderer
  }).parse(markdown, { async: false });

  return { html, headings };
};

const decodeHtmlEntities = (value) =>
  value
    .replace(/&#(\d+);/g, (_match, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_match, code) => String.fromCodePoint(Number.parseInt(code, 16)))
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');

const htmlToPlainText = (html) =>
  decodeHtmlEntities(html.replace(/<[^>]*>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();

const truncateSearchText = (text) =>
  text.length > SEARCH_SECTION_TEXT_LIMIT ? `${text.slice(0, SEARCH_SECTION_TEXT_LIMIT - 1).trimEnd()}…` : text;

/**
 * Splits a markdown document into search sections: the intro before the first
 * heading (depth 0), then one section per heading. Heading ids reuse the exact
 * slugify + uniqueness rules of the HTML registry renderer above so every
 * non-null `headingId` matches a registry heading id for the same document.
 */
const buildSearchSections = (markdown) => {
  const marked = new Marked({ async: false, breaks: false, gfm: true, pedantic: false });
  const tokens = marked.lexer(markdown);
  const usedHeadingIds = new Set();
  const sections = [];
  let current = { headingId: null, heading: null, depth: 0, bodyTokens: [] };

  const flushCurrentSection = () => {
    const text = truncateSearchText(htmlToPlainText(marked.parser(current.bodyTokens)));

    if (current.heading !== null || text.length > 0) {
      sections.push({ headingId: current.headingId, heading: current.heading, depth: current.depth, text });
    }
  };

  for (const token of tokens) {
    if (token.type !== 'heading') {
      current.bodyTokens.push(token);
      continue;
    }

    flushCurrentSection();

    const baseId = slugifyMarkdownHeading(token.text);
    let headingId = null;

    if (baseId) {
      headingId = getUniqueMarkdownHeadingId(baseId, usedHeadingIds);
      usedHeadingIds.add(headingId);
    }

    current = { headingId, heading: htmlToPlainText(marked.parser([token])), depth: token.depth, bodyTokens: [] };
  }

  flushCurrentSection();

  return sections;
};

const files = (await readdir(docsInputDirectory))
  .filter((file) => file.endsWith('.md'))
  .sort((first, second) => first.localeCompare(second));

const markdownSources = await Promise.all(
  files.map(async (file) => {
    const markdown = await readFile(join(fileURLToPath(docsInputDirectory), file), 'utf8');

    return [`/docs/${basename(file)}`, markdown];
  })
);

const entries = markdownSources.map(([key, markdown]) => [key, renderMarkdown(markdown)]);
const searchEntries = markdownSources.map(([key, markdown]) => [key, { sections: buildSearchSections(markdown) }]);

const prettierOptions = (await resolveConfig(fileURLToPath(docsOutputFile))) ?? {};
const output = await format(
  `/* eslint-disable max-lines -- generated docs HTML registry */
/* This file is generated by tools/generate-showcase-docs.mjs. */

export type DocsHtmlHeading = {
  readonly depth: number;
  readonly id: string;
};

export type DocsHtmlEntry = {
  readonly html: string;
  readonly headings: readonly DocsHtmlHeading[];
};

export const docsHtmlRegistry = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const satisfies Readonly<
  Record<string, DocsHtmlEntry>
>;

export const findDocsHtmlEntry = (markdownPath: string): DocsHtmlEntry | undefined => {
  return (docsHtmlRegistry as Readonly<Record<string, DocsHtmlEntry>>)[markdownPath];
};
`,
  { ...prettierOptions, filepath: fileURLToPath(docsOutputFile), parser: 'typescript' }
);

const searchIndexOutput = await format(
  `/* eslint-disable max-lines -- generated docs search index */
/* This file is generated by tools/generate-showcase-docs.mjs. Section bodies are
   plain text with markdown/HTML formatting stripped, whitespace collapsed, and
   truncated to ${SEARCH_SECTION_TEXT_LIMIT} characters per section. */

export type DocsSearchSection = {
  /** Registry heading id for fragment navigation; null for the intro section before the first heading. */
  readonly headingId: string | null;
  readonly heading: string | null;
  /** Heading depth (1-6); 0 for the intro section. */
  readonly depth: number;
  readonly text: string;
};

export type DocsSearchDocument = {
  readonly sections: readonly DocsSearchSection[];
};

export const docsSearchIndex: Readonly<Record<string, DocsSearchDocument>> = ${JSON.stringify(Object.fromEntries(searchEntries), null, 2)};
`,
  { ...prettierOptions, filepath: fileURLToPath(searchIndexOutputFile), parser: 'typescript' }
);

await mkdir(new URL('./', docsOutputFile), { recursive: true });
await writeFile(docsOutputFile, output);
await writeFile(searchIndexOutputFile, searchIndexOutput);
